#pragma once

#include <QHash>
#include <QList>
#include <QStringList>
#include <QString>
#include <QVariantMap>

#include <optional>

namespace agv {

// One app excluded from the VPN. The id doubles as the cgroup directory name.
struct AppRule {
    QString id;            // "app-1a2b3c4d", generated by the daemon
    QString name;          // shown in the GUI
    QString icon;          // icon name or path, optional
    QString desktopFile;   // "firefox.desktop", optional
    QString exe;           // absolute path matched by the exec watcher (stage 5), optional
    QString cmdlineMatch;  // substring of the command line, for Wine games (stage 5), optional
    bool enabled = true;
    qint64 ownerUid = -1;  // set by the daemon from the D-Bus caller; -1 matches every user

    bool operator==(const AppRule &) const = default;
};

// The persisted app exclusions (JSON in the daemon's data directory). Like the CLI's site lists,
// each mode keeps its own list: the apps that skip the VPN and the apps that alone use it.
class AppStore
{
public:
    explicit AppStore(QString path);

    // Loads the file; a missing file is an empty list. Returns an error message on failure.
    QString load();
    QString save() const;

    // The current mode's list; every call below works on it.
    const QList<AppRule> &rules() const;

    // "bypass" (listed apps skip the VPN) or "vpn-only" (only listed apps use it).
    QString mode() const { return m_mode; }
    void setMode(const QString &mode) { m_mode = mode; }
    static QStringList modes() { return {QStringLiteral("bypass"), QStringLiteral("vpn-only")}; }
    static bool isValidMode(const QString &mode);
    const AppRule *find(const QString &id) const;

    // Builds a rule from D-Bus fields (name, icon, desktop_file, exe, cmdline_match, enabled).
    // With base set, unspecified fields keep the base's values. Returns an error message or
    // the rule.
    static std::optional<AppRule> fromMap(const QVariantMap &map, QString *error,
                                          const AppRule *base = nullptr);
    static QVariantMap toMap(const AppRule &rule);
    static bool isValidId(const QString &id);

    // Adds a rule with a fresh id and returns that id.
    QString add(AppRule rule);
    bool replace(const AppRule &rule);
    void setRules(QList<AppRule> rules) { m_rules[m_mode] = std::move(rules); }
    bool remove(const QString &id);

private:
    // An app's id is unique across both lists: it names the app's cgroup.
    bool idTaken(const QString &id) const;

    QString m_path;
    QHash<QString, QList<AppRule>> m_rules;  // mode → its list
    QString m_mode = QStringLiteral("bypass");
};

} // namespace agv
